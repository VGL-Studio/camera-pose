def placement_rows(coded, kept, examples):
    rows = []
    for p in coded:
        row = dict(p)
        screen, when, note = APP_WIDE_TEXT.get(p["code"], (None, None, None))
        if p["code"] in KNOWN_PLACEMENTS:
            screen, when = KNOWN_PLACEMENTS[p["code"]]
        row.update(screen=screen, when=when, launch="-" if p["wide"] == "Có" else "Tắt", image=None,
                   status="Đã code", note=note or p["note"] or None)
        old = next((k for k in kept if k.get(HEADER_OF["code"]) == p["code"]), None)
        if old:
            for k in USER_FIELDS:
                if old.get(HEADER_OF[k]) not in (None, ""):
                    row[k] = old[HEADER_OF[k]]
            if row["status"] in ("Đề xuất", "Đã duyệt trong spec"):
                row["status"] = "Đã code"
        row["coded"] = True
        rows.append(row)
    coded_codes = {p["code"] for p in coded}
    for old in kept:
        if old.get(HEADER_OF["code"]) not in coded_codes:
            rows.append({k: old.get(HEADER_OF[k]) for k in PL_KEYS} | {"coded": False})
    kept_codes = {old.get(HEADER_OF["code"]) for old in kept}
    if examples:
        for code, fmt, screen, when, group, seconds, every, policy, launch, note in EXAMPLE_PLACEMENTS:
            if code not in coded_codes and code not in kept_codes:
                rows.append({"code": code, "format": fmt, "wide": "Không", "screen": screen, "when": when,
                             "group": group, "seconds": seconds, "every": every, "policy": policy, "launch": launch,
                             "image": None, "status": EXAMPLE, "note": note, "coded": False})
    return rows


