def app_name():
    settings = ROOT / "settings.gradle.kts"
    match = re.search(r'rootProject\.name\s*=\s*"([^"]+)"', settings.read_text()) if settings.exists() else None
    return match.group(1) if match else ROOT.name


def read_placements(with_staging):
    """One-line declarations of AdPlacement, as scripts/release.sh reads them."""
    found = sorted((ROOT / "core/ads/src/main").glob("**/AdPlacement.kt"))
    if len(found) != 1:
        sys.exit(f"Cần đúng một AdPlacement.kt trong core/ads/src/main, thấy {len(found)}.")
    text = found[0].read_text()
    formats = dict(re.findall(r'^\s*([A-Z_]+)\("([a-z_]+)"\),', text.split("enum class AdPlacement")[0], re.M))
    body = text.split("enum class AdPlacement", 1)[1]
    # A long line may name its interval group by a constant (docs/ops/ads-guide.md, section 5, step 2).
    group_constants = dict((n, (g, int(sec))) for n, g, sec in re.findall(
        r'val\s+([A-Za-z_][A-Za-z0-9_]*)\s*=\s*AdIntervalGroup\.named\("([a-z0-9_]+)",\s*(\d+)L?\)', text))
    placements, comment = [], []
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith(("/**", "*", "//")):
            comment.append(re.sub(r"^(/\*\*|\*/|\*|//)\s?", "", stripped).rstrip("*/ ").strip())
            continue
        match = re.match(r'^[A-Z_]+\("([a-z0-9_]+)",\s*AdFormat\.([A-Z_]+)(.*)\),$', stripped)
        if not match:
            comment = []
            if stripped == ";":
                break
            continue
        code, fmt, attrs = match.groups()
        note = " ".join(c for c in comment if c).strip()
        comment = []
        if code.startswith(STAGING_PREFIX) and not with_staging:
            continue
        group = re.search(r'AdIntervalGroup\.named\("([a-z0-9_]+)",\s*(\d+)', attrs)
        named = re.search(r"intervalGroup\s*=\s*([A-Za-z_][A-Za-z0-9_]*)\s*(,|$)", attrs)
        group = (group.group(1), int(group.group(2))) if group else group_constants.get(named.group(1)) if named else None
        every = re.search(r"nativeEvery\s*=\s*(\d+)", attrs)
        policy = re.search(r"RewardedNoAdPolicy\.(AllowAfter\((\d+)\)|Block|Allow)(?![A-Za-z])", attrs)
        policy_code = None
        if policy:
            policy_code = "allow_after_" + policy.group(2) if policy.group(2) else policy.group(1).lower()
        extras = [name for name in ("ignoreInterval", "ctaLarge", "keepSpaceWhenPoolEmpty")
                  if re.search(name + r"\s*=\s*true", attrs)]
        if re.search(r"recordInterval\s*=\s*false", attrs):
            extras.append("recordInterval = false")
        placements.append({
            "code": code, "format": formats.get(fmt, fmt.lower()), "wide": "Có" if "appWide = true" in attrs else "Không",
            "group": group[0] if group else None, "seconds": group[1] if group else None,
            "every": int(every.group(1)) if every else None, "policy": policy_code,
            "note": "; ".join(filter(None, [note, ", ".join(extras)])),
        })
    return placements


def read_keys():
    """Rows of the generated key table: key, type, default, module, description."""
    if not KEYS_FILE.exists():
        sys.exit(f"Không thấy {KEYS_FILE}. Sinh bảng khóa trước: "
                 "./gradlew :app:testStagingDebugUnitTest -PremoteConfigKeys.update=true")
    rows = []
    for line in KEYS_FILE.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 5 and cells[0].startswith("`"):
            rows.append({"key": cells[0].strip("`"), "type": cells[1], "default": cells[2].strip("`").strip('"'),
                         "module": cells[3].strip("`"), "description": cells[4]})
    return rows


def read_events():
    """`const val EVENT_X = "name"` in the main sources of every module, with the module name."""
    events = {}
    for path in sorted(ROOT.glob("**/src/main/**/*.kt")):
        parts = path.relative_to(ROOT).parts
        if "build" in parts or any(part.startswith(".") for part in parts):
            continue
        for name in re.findall(r'const val EVENT_[A-Z0-9_]+\s*=\s*"([a-z0-9_]+)"', path.read_text()):
            module = parts[: parts.index("src")]
            events.setdefault(name, ":" + ":".join(module))
    return events


