"""Writes the ads, Remote Config and events planning workbook of this app (.xlsx), from the code of the app.
How the team uses it: docs/ops/ads-plan.md.

Usage: scripts/ads-plan.py [--out <file.xlsx>] [--keep <older file.xlsx>] [--with-staging] [--no-examples] [--dump]
  --out           where to write; default build/ads-plan/<app name>_Ads_RC_Events.xlsx (not in git)
  --keep          carry over what the team filled in an older workbook: screens, timing, launch values, status,
                  notes, planned placements and keys not in the code yet, the app's own events
  --with-staging  also list the placements of the staging ad gallery (gallery_...)
  --no-examples   leave out the example rows (an app with its own placements does not need them)
  --dump          print what would go in the workbook as JSON, write nothing (tests; needs no openpyxl unless --keep)

Sources, read every run so the workbook always matches the code of this app:
  - AdPlacement.kt of :core:ads (any package, an app renames it): one-line placement declarations (the same rule as scripts/release.sh) and the
    AdFormat codes;
  - docs/remote-config-keys.md: every Remote Config key with its type, default, module and description (generated by
    RemoteConfigKeysTest; run ./gradlew :app:testStagingDebugUnitTest -PremoteConfigKeys.update=true first);
  - `const val EVENT_* = "..."` in the main sources of every module: the app's own analytics events.
The ad events sent by :core:ads and :core:analytics and the fixed constants follow docs/ops/ads-business-rules.md
(sections 8 and 11) and are written from the tables below. The workbook is for the team, so its text is in
Vietnamese. ADS_PLAN_ROOT overrides the repository root (tests). Writing or reading a workbook needs openpyxl
(pip install openpyxl); it is imported only then, so --dump runs on a machine without it (CI).
"""

