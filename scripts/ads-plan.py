def rows_by_header(ws, header_row=4):
    names = [c.value for c in ws[header_row]]
    for row in ws.iter_rows(min_row=header_row + 1, values_only=True):
        yield {n: v for n, v in zip(names, row) if n}


def is_formula(value):
    return isinstance(value, str) and value.startswith("=")


def read_kept(path):
    wb = load_workbook(path)
    kept = {"placements": [], "launch": {}, "keys": [], "events": {}}
    if "Vị trí QC" in wb.sheetnames:
        for row in rows_by_header(wb["Vị trí QC"]):
            code = row.get("Mã vị trí")
            if code and not is_formula(code) and row.get("Trạng thái") != EXAMPLE:
                kept["placements"].append({k: v for k, v in row.items() if not is_formula(v)})
    if "Remote Config" in wb.sheetnames:
        for row in rows_by_header(wb["Remote Config"]):
            key = row.get("Khóa")
            if not key or is_formula(key) or "<" in key:
                continue
            if not is_formula(row.get("Giá trị phát hành")):
                kept["launch"][key] = row.get("Giá trị phát hành")
            if row.get("Nhóm") == "Khóa của app":
                kept["keys"].append(row)
    if "Sự kiện" in wb.sheetnames:
        for row in rows_by_header(wb["Sự kiện"]):
            name = row.get("Tên sự kiện")
            if name and row.get("Nhóm") == "Sự kiện của app" and row.get("Trạng thái") != EXAMPLE:
                kept["events"][name] = row
    return kept


